const VOWELS = ['а', 'е', 'ё', 'и', 'о', 'у', 'ы', 'э', 'ю', 'я'];

function getVowelIndices(word) {
  const lower = word.toLowerCase();
  const indices = [];
  for (let i = 0; i < lower.length; i++) {
    if (VOWELS.includes(lower[i])) indices.push(i);
  }
  return indices;
}

function makeStressedWord(lowerWord, stressIndex) {
  let result = '';
  for (let i = 0; i < lowerWord.length; i++) {
    if (i === stressIndex) {
      result += lowerWord[i].toUpperCase();
    } else {
      result += lowerWord[i].toLowerCase();
    }
  }
  return result;
}

function detectPartOfSpeech(word, stressed) {
  const w = word.toLowerCase();
  if (w.endsWith('ть') || w.endsWith('ться') || w.endsWith('ит') || w.endsWith('ится') || w.endsWith('ат') || w.endsWith('ут') || w.endsWith('ют') || w.endsWith('ла') || w.endsWith('лась') || w.endsWith('ло') || w.endsWith('лось') || w.endsWith('ли') || w.endsWith('лись') || w.endsWith('нул') || w.endsWith('ал') || w === 'положил') {
    return 'глагол';
  }
  if (w.endsWith('в') || w.endsWith('вшись')) {
    return 'деепричастие';
  }
  if (w.endsWith('нный') || w.endsWith('тый') || w.endsWith('вший') || w.endsWith('вшийся') || w.endsWith('щий') || (w.endsWith('ая') && stressed.endsWith('А')) || w === 'снята' || w === 'занята' || w === 'заселена' || w === 'принята') {
    return 'причастие';
  }
  if (w.endsWith('ее') || w.endsWith('ый') || w.endsWith('ий') || w.endsWith('ой') || w.endsWith('овый') || w.endsWith('евший') || w === 'прозорлива' || w === 'верна' || w === 'ловка') {
    return 'прилагательное';
  }
  if (w === 'вовремя' || w === 'доверху' || w === 'донельзя' || w === 'донизу' || w === 'досуха' || w === 'засветло' || w === 'затемно' || w === 'надолго' || w === 'ненадолго' || w === 'наверх' || w === 'добела') {
    return 'наречие';
  }
  return 'существительное';
}

const finalTask4List = [];
let t4Count = 1;
const seenTask4Words = new Set();

task4FullRawList.forEach(rawItem => {
  const stressed = rawItem.trim();
  const lower = stressed.toLowerCase();
  const vowelIndices = getVowelIndices(lower);

  if (vowelIndices.length <= 1) {
    return; // односложное
  }

  // Найти ударную гласную
  let correctIndex = -1;
  for (let i = 0; i < stressed.length; i++) {
    const ch = stressed[i];
    if (ch === ch.toUpperCase() && VOWELS.includes(ch.toLowerCase())) {
      correctIndex = i;
      break;
    }
  }

  if (correctIndex === -1) {
    console.warn('Не найдено ударение в:', rawItem);
    return;
  }

  // Дедупликация идентичных записей (например если дублируется в списке)
  const key = stressed;
  if (seenTask4Words.has(key)) return;
  seenTask4Words.add(key);

  const otherIndices = vowelIndices.filter(idx => idx !== correctIndex);
  if (otherIndices.length === 0) return;

  const wrongVariants = [];
  otherIndices.forEach(idx => {
    const variant = makeStressedWord(lower, idx);
    if (variant !== stressed && !wrongVariants.includes(variant)) {
      wrongVariants.push(variant);
    }
  });

  const partOfSpeech = detectPartOfSpeech(lower, stressed);

  finalTask4List.push({
    id: `t4_${String(t4Count++).padStart(3, '0')}`,
    word: lower,
    correct: stressed,
    wrong: wrongVariants,
    partOfSpeech: partOfSpeech,
    firstLetter: lower[0]
  });
});

